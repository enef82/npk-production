"""Обработчики регистрируются через `autodiscover_modules("handlers")` (см. registry.py) —
`core.events` не должен статически импортировать ни один функциональный модуль. Это
проверяет `lint-imports` по всему дереву импортов, а не только по `registry.py`
(см. аналогичный `test_реестр_профилей_не_нарушает_границы` в `core.identity`).

Вызывается `importlinter.cli.lint_imports()` напрямую в процессе теста, а не через
`subprocess.run(["lint-imports"])`: имя бинарника ищется в `PATH`, а его состав зависит
от того, чем запущен pytest (`uv run`, docker, голый интерпретатор `.venv`) — на части
путей `lint-imports` в `PATH` не попадает, и тест падает не на нарушении границ, а на
`FileNotFoundError` окружения. Прямой вызов использует тот же интерпретатор и то же
окружение, что и сам тест, поэтому результат не зависит от способа запуска.
"""

from importlinter.cli import lint_imports


def test_обработчики_не_нарушают_границы_модулей() -> None:
    assert lint_imports() == 0, "import-linter нашёл нарушение границ — см. вывод выше"
